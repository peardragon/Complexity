from __future__ import annotations

import argparse

from utils.dataset_builder import build_datasets


def main() -> None:
    parser = argparse.ArgumentParser(description="Validate existing MNIST manual-rule dataset payloads.")
    parser.add_argument(
        "--overwrite",
        action="store_true",
        help="Accepted for interface parity; raw MNIST payloads are not regenerated by this stage.",
    )
    args = parser.parse_args()
    counts = build_datasets(overwrite=bool(args.overwrite))
    print(
        "datasets "
        f"validated={counts['validated']} "
        f"metadata_written={counts['metadata_written']} "
        f"missing={counts['missing']}"
    )


if __name__ == "__main__":
    main()

